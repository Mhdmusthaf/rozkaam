// Generates src/ui/brand-paths.ts and the app icon / splash PNGs from the
// SVG logo files in <repo>/brand. Run: node scripts/brand.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const brand = join(root, '..', '..', 'brand');

const mark = readFileSync(join(brand, 'logomark-colour.svg'), 'utf8');
const word = readFileSync(join(brand, 'wordmark-colour.svg'), 'utf8');

const paths = (svg, cls) =>
  [...svg.matchAll(/<path class="([^"]+)" d="([^"]+)"/g)].filter((m) => !cls || m[1] === cls).map((m) => m[2]);
const ellipses = [...mark.matchAll(/<ellipse[^>]*cx="([\d.]+)" cy="([\d.]+)" rx="([\d.]+)" ry="([\d.]+)"/g)].map(
  (m) => ({ cx: +m[1], cy: +m[2], rx: +m[3], ry: +m[4] }),
);

const data = {
  markAccent: paths(mark, 'cls-1'), // grey "pillar" pieces
  markMain: paths(mark, 'cls-2'), // violet ribbon
  markDots: ellipses,
  word: paths(word),
};

mkdirSync(join(root, 'src', 'ui'), { recursive: true });
writeFileSync(
  join(root, 'src', 'ui', 'brand-paths.ts'),
  `// Generated by scripts/brand.mjs from /brand/*.svg. Do not edit by hand.\n` +
    `export const MARK_VIEWBOX = '330 390 1260 1140';\n` +
    `export const WORD_VIEWBOX = '270 490 1376 220';\n` +
    `export const MARK_ACCENT = ${JSON.stringify(data.markAccent)};\n` +
    `export const MARK_MAIN = ${JSON.stringify(data.markMain)};\n` +
    `export const MARK_DOTS = ${JSON.stringify(data.markDots)};\n` +
    `export const WORD = ${JSON.stringify(data.word)};\n`,
);

// ---- raster icons -------------------------------------------------------
const markSvg = (main, accent, size, pad, bg) => {
  // logomark content box is ~1260 x 1140 starting at (330, 390)
  const box = 1260;
  const scale = (size * (1 - pad * 2)) / box;
  const tx = size * pad - 330 * scale;
  const ty = (size - 1140 * scale) / 2 - 390 * scale;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  ${bg ? `<rect width="${size}" height="${size}" fill="${bg}"/>` : ''}
  <g transform="translate(${tx} ${ty}) scale(${scale})">
    ${data.markAccent.map((d) => `<path fill="${accent}" d="${d}"/>`).join('')}
    ${data.markDots.map((e) => `<ellipse fill="${main}" cx="${e.cx}" cy="${e.cy}" rx="${e.rx}" ry="${e.ry}"/>`).join('')}
    ${data.markMain.map((d) => `<path fill="${main}" d="${d}"/>`).join('')}
  </g></svg>`;
};

const out = join(root, 'assets', 'images');
const VIOLET = '#6601F9';
const png = (svg, file) => sharp(Buffer.from(svg)).png().toFile(join(out, file));

await png(markSvg('#FFFFFF', '#D9C7FF', 1024, 0.2, VIOLET), 'icon.png');
await png(markSvg('#FFFFFF', '#D9C7FF', 1024, 0.28, null), 'android-icon-foreground.png');
await png(`<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect width="1024" height="1024" fill="${VIOLET}"/></svg>`, 'android-icon-background.png');
await png(markSvg('#000000', '#000000', 1024, 0.28, null), 'android-icon-monochrome.png');
await png(markSvg('#FFFFFF', '#D9C7FF', 512, 0.08, null), 'splash-icon.png');
await png(markSvg('#FFFFFF', '#D9C7FF', 96, 0.14, VIOLET), 'favicon.png');
console.log('brand assets written');
