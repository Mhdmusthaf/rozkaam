// File storage for KYC documents and check-in photos. Local disk now;
// Cloudflare R2 implements the same three functions later.
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { env } from '../env';

const ALLOWED: Record<string, string> = { 'image/jpeg': 'jpg', 'image/png': 'png', 'image/webp': 'webp', 'application/pdf': 'pdf' };
export const MAX_UPLOAD_BYTES = 8 * 1024 * 1024;

export const isAllowedType = (contentType: string) => contentType in ALLOWED;

export async function saveFile(bytes: Uint8Array, contentType: string): Promise<string> {
  const key = `${randomUUID()}.${ALLOWED[contentType]}`;
  await mkdir(env.UPLOAD_DIR, { recursive: true });
  await writeFile(join(env.UPLOAD_DIR, key), bytes);
  return key;
}

export async function readStoredFile(key: string): Promise<Uint8Array> {
  // Keys are generated by saveFile; refuse anything that could leave the folder.
  if (!/^[0-9a-f-]{36}\.(jpg|png|webp|pdf)$/.test(key)) throw new Error('bad file key');
  return readFile(join(env.UPLOAD_DIR, key));
}
